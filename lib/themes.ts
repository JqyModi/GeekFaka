export function normalizeSiteTheme(value?: string | null): SiteTheme {
  return SITE_THEMES.some((theme) => theme.value === value)
    ? (value as SiteTheme)
    : DEFAULT_SITE_THEME;
}

export function getSiteThemeClassName(value?: string | null) {
  return `theme-${normalizeSiteTheme(value)}`;
}

export function getSiteThemeVariables(value?: string | null) {
  return SITE_THEME_VARIABLES[normalizeSiteTheme(value)];
}
